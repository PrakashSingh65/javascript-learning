// Qs.  Use switch statement to print the day of the week using a number variable 'day' with value 1 to 7.

//  1= Monday, 2 = Tuesday &so on.

let day = 4;

switch (day) {
  case 1:
    console.log("mmonday");
    break;

    case2: console.log("tuesday");
    break;
    case3: console.log("wednesday");
    break;

  case 4:
    console.log("thursday");
    break;

  case 5:
    console.log("friday");
    break;

  case 6:
    console.log("saturday");
    break;

  case 7:
    console.log("sunday");
    break;

  default:
    console.log("invalid day");
}
